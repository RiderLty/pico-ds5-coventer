// 改动纪律（每次改这段前先读）：这里的每条规则都在直接决定 token 消耗——
//   · "先看大纲、只读要改的区间" 决定每轮的**新增量 M**；
//   · "一次把所有改动放进同一个 edits 数组" 决定**轮数 N**；
//   · "不需要回读确认" 删掉的是旧版最贵的一条仪式（编辑成功后模型还会
//     read_current_script 把整页再读一遍，8KB × 每轮重发）。
